/**
 * Helper to shuffle array elements randomly using Fisher-Yates
 */
export function shuffleArray<T>(array: T[]): T[] {
  const shuffled = [...array];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
}

/**
 * Scramble patient scenarios (names, ages, clinical details) for offline testing
 */
export function scramblePatientScenario(q: Question): Question {
  const maleNames = ['张大伯', '李先生', '王大爷', '赵师傅', '小刘', '孙大叔', '周先生', '吴大哥'];
  const femaleNames = ['陈大娘', '李女士', '赵大妈', '张大姐', '小吴', '周阿姨', '林女士', '钱大婶'];
  const ages = [26, 32, 41, 53, 62, 68, 74];

  const isFemale = Math.random() > 0.5;
  const name = isFemale
    ? femaleNames[Math.floor(Math.random() * femaleNames.length)]
    : maleNames[Math.floor(Math.random() * maleNames.length)];
  const age = ages[Math.floor(Math.random() * ages.length)];

  let text = q.question;
  text = text.replace(/一位\d+岁的(男性|女性|老太太|患者)/, `一位 ${age} 岁的${isFemale ? '女性' : '男性'}患者 (${name})`);
  text = text.replace(/患者，\d+岁/, `${name}，${age}岁`);

  return {
    ...q,
    question: text
  };
}

/**
 * Shuffles question list AND options order for each question while accurately preserving correct answer matching!
 */
export function buildRandomizedExamPaper(questionsPool: Question[], maxCount: number = 5): Question[] {
  if (!questionsPool || questionsPool.length === 0) return [];

  // 1. Shuffle the questions list
  const shuffledQuestions = shuffleArray(questionsPool).slice(0, maxCount);

  // 2. For EACH question, shuffle its options while maintaining the answer string!
  return shuffledQuestions.map((q) => {
    // Scramble clinical name/age if applicable
    const scrambled = scramblePatientScenario(q);

    if (!scrambled.options || scrambled.options.length <= 1) return scrambled;

    // Shuffle options array
    const shuffledOptions = shuffleArray(scrambled.options);

    return {
      ...scrambled,
      options: shuffledOptions,
      // Answer string remains the same correct text option
      answer: scrambled.answer
    };
  });
}

/**
 * Retrieves a full set of questions for a specific LevelGate
 */
export function getStandardizedQuestionsForGate(gate: LevelGate, levelTopics: Topic[]): Question[] {
  // 1. Gather all exam & practice questions from all topics in the gate
  const topicQuestions = levelTopics.flatMap((t) => [
    ...(t.examQuestions || []),
    ...(t.practiceQuestions || [])
  ]);

  // 2. Gather standardized questions specifically created for this gate ID
  const gatePresetQuestions = STANDARDIZED_GATE_QUESTIONS[gate.id] || [];

  // 3. Fallback to generic chapter standardized questions if empty
  const chapterPresetQuestions = STANDARDIZED_GATE_QUESTIONS[`g${gate.chapterId.replace('ch', '')}_1`] || [];

  // 4. Combine all question sources
  const combined = [...gatePresetQuestions, ...topicQuestions, ...chapterPresetQuestions];

  // Remove exact question string duplicates
  const uniqueQuestions: Question[] = [];
  const seenTexts = new Set<string>();

  for (const q of combined) {
    if (!seenTexts.has(q.question)) {
      seenTexts.add(q.question);
      uniqueQuestions.push(q);
    }
  }

  return uniqueQuestions;
}
